export const PLACES = [];
const seen = new Set();
GROUPS.forEach(g => g.list.forEach(k => {
  if (seen.has(k)) return;          // กันชื่อซ้ำระหว่างกลุ่ม
  seen.add(k);
  PLACES.push({ name: k, kind: g.kind, abroad: g.abroad, note: g.note });
}));

/* เรียงชื่อยาวไว้ก่อน เพื่อให้ "เกาะสมุย" ชนะ "สมุย"
   และ "พระนครศรีอยุธยา" ชนะ "อยุธยา" ตอนค้นในประโยค */
export const PLACES_BY_LENGTH = PLACES.slice().sort((a, b) => b.name.length - a.name.length);

export function findPlaceIn(text) {
  return PLACES_BY_LENGTH.find(p => text.includes(p.name)) || null;
}

export function lookupPlace(text) {
  const t = String(text || '').trim();
  if (!t) return null;
  return PLACES_BY_LENGTH.find(p => p.name === t) || PLACES_BY_LENGTH.find(p => t.includes(p.name)) || null;
}
